import { stringify } from 'yaml';
import { describe, problems, toToml, text } from './module';
import type { Resolution } from './resolve';
import type { CatalogIndex, Config, Engine, EnvVar, Module } from './types';

export const IMAGE = 'ghcr.io/joostme/container-agent';
export const CONFIG_DIR = '/etc/container-agent';
export const AGENT_HOME = '/home/agent';
export const AGENT_SCHEMA_URL =
	'https://raw.githubusercontent.com/joostme/container-agent/main/schema/v1/agent.schema.json';

export interface Port {
	module: string;
	variable: string;
	protocol: 'http' | 'tcp';
	port: string;
}

export interface Step {
	/** Plain text and commands to run on the Docker host. */
	parts: { text: string; command: boolean }[];
}

export interface File {
	/** Path relative to the folder with compose.yaml. */
	path: string;
	text: string;
}

export interface Output {
	files: File[];
	steps: Step[];
	warnings: string[];
	ports: Port[];
}

export function defaultConfig(engines: Engine[]): Config {
	return {
		image: engines[0]?.image ?? 'latest',
		catalog: '',
		modules: {},
		pins: {},
		custom: [],
		values: {},
		puid: '1000',
		pgid: '1000',
		workspace: '/repos',
		autoUpdate: true,
		service: 'agent',
		tz: '',
		dataDir: './data',
		sshKeys: '',
		inline: false
	};
}

export const customModules = (config: Config): Module[] => config.custom.map((doc) => describe(doc));

/** The value a module variable gets in the container. */
export function effectiveValue(config: Config, variable: EnvVar): string {
	return config.values[variable.name] || variable.default;
}

export function portsOf(config: Config, modules: Module[]): Port[] {
	return modules.flatMap((module) =>
		module.env
			.filter((variable) => variable.type === 'port')
			.map((variable) => ({
				module: module.name,
				variable: variable.name,
				protocol: variable.protocol ?? 'tcp',
				port: effectiveValue(config, variable)
			}))
	);
}

const quote = (value: string) => JSON.stringify(value);
const bareKey = (name: string) => (/^[A-Za-z0-9_-]+$/.test(name) ? name : quote(name));

function agentToml(config: Config, resolution: Resolution): string {
	const lines = [
		`#:schema ${AGENT_SCHEMA_URL}`,
		'# Generated by the container-agent configurator; load it there again to change it.',
		'format = 1',
		`puid = ${Number.parseInt(config.puid, 10) || 1000}`,
		`pgid = ${Number.parseInt(config.pgid, 10) || 0}`
	];
	if (config.workspace && config.workspace !== '/repos') lines.push(`workspace = ${quote(config.workspace)}`);
	if (!config.autoUpdate) lines.push('auto_update = false');
	if (config.catalog) lines.push(`catalog = ${quote(config.catalog)}`);

	lines.push('', '[modules]');
	const enabled = resolution.order.map((m) => m.name);
	const picked = enabled.filter((n) => n in config.modules).sort();
	const required = enabled.filter((n) => !(n in config.modules) && resolution.source.get(n)?.kind === 'catalog');
	const local = enabled.filter((n) => resolution.source.get(n)?.kind === 'local').sort();
	for (const name of picked) {
		const spec = config.modules[name];
		lines.push(`${bareKey(name)} = ${quote(spec)}`);
	}
	for (const name of required.sort()) {
		const source = resolution.source.get(name);
		const by = resolution.requiredBy.get(name) ?? [];
		if (source?.kind === 'catalog') {
			lines.push(`${bareKey(name)} = ${quote(source.version)}   # required by ${by.join(', ')}`);
		}
	}
	for (const name of local) lines.push(`${bareKey(name)} = "local"   # modules/${name}.toml`);
	// modules picked but not resolvable keep their entry, so nothing is lost
	for (const [name, spec] of Object.entries(config.modules)) {
		if (!enabled.includes(name)) lines.push(`${bareKey(name)} = ${quote(spec)}`);
	}

	const values: string[] = [];
	for (const module of resolution.order) {
		for (const variable of module.env) {
			const value = config.values[variable.name] ?? '';
			if (variable.type === 'secret' || !value || value === variable.default) continue;
			values.push(`${variable.name} = ${quote(value)}`);
		}
	}
	if (values.length) lines.push('', '[env]', ...values);
	return `${lines.join('\n')}\n`;
}

function envFile(config: Config, modules: Module[]): string {
	const secrets = modules.flatMap((m) => m.env.filter((v) => v.type === 'secret'));
	if (!secrets.length) return '# No secrets needed for these modules\n';
	const lines = ['# Secrets for the container; keep this file next to compose.yaml and out of git'];
	for (const variable of secrets) {
		lines.push('');
		if (variable.description) lines.push(`# ${variable.description}${variable.required ? ' (required)' : ''}`);
		lines.push(`${variable.name}=${config.values[variable.name] ?? ''}`);
	}
	return `${lines.join('\n')}\n`;
}

function compose(config: Config, ports: Port[], configFiles: File[], hasSecrets: boolean): string {
	const volumes: string[] = [];
	if (!config.inline) volumes.push(`./config:${CONFIG_DIR}:ro`);
	volumes.push(`${config.dataDir}/home:${AGENT_HOME}`, `${config.dataDir}/repos:${config.workspace || '/repos'}`);
	if (config.sshKeys) volumes.push(`${config.sshKeys}:${AGENT_HOME}/.ssh-keys:ro`);

	const service: Record<string, unknown> = {
		image: `${IMAGE}:${config.image}`,
		container_name: config.service,
		hostname: config.service,
		restart: 'unless-stopped'
	};
	if (hasSecrets) service.env_file = '.env';
	if (config.tz) service.environment = { TZ: config.tz };
	service.volumes = volumes;
	const published = [...new Set(ports.map((p) => p.port))];
	if (published.length) service.ports = published.map((p) => `${p}:${p}`);

	const doc: Record<string, unknown> = { services: { [config.service]: service } };
	if (config.inline) {
		// compose replaces $VAR in the content too; $$ keeps a literal $
		const configs: Record<string, { content: string }> = {};
		service.configs = configFiles.map((file) => {
			const source = `${config.service}-${file.path.replace(/^config\//, '').replace(/[/.]/g, '-')}`;
			configs[source] = { content: file.text.replaceAll('$', '$$$$') };
			return { source, target: `${CONFIG_DIR}/${file.path.replace(/^config\//, '')}` };
		});
		doc.configs = configs;
	}

	const header = [
		'# Generated by the container-agent configurator; load it there again to change it.',
		config.inline
			? '# Start: docker compose up -d   Logs: docker compose logs -f   Needs Docker Compose 2.23 or later'
			: '# Start: docker compose up -d   Logs: docker compose logs -f   Settings: config/agent.toml',
		''
	].join('\n');
	return header + stringify(doc, { lineWidth: 0 });
}

function steps(config: Config, modules: Module[]): Step[] {
	const exec = `docker compose exec ${config.service} `;
	const toStep = (text: string): Step => ({
		parts: text
			.split(/(`[^`]+`)/)
			.filter(Boolean)
			.map((part) =>
				part.startsWith('`') ? { text: exec + part.slice(1, -1), command: true } : { text: part, command: false }
			)
	});
	const start: Step[] = [
		{
			parts: [
				{
					text: config.inline
						? 'Put compose.yaml and .env into one folder. '
						: 'Put compose.yaml, .env and the config folder into one folder (Download all). ',
					command: false
				},
				{ text: 'Start the container: ', command: false },
				{ text: 'docker compose up -d', command: true },
				{ text: '. The first start installs all tools and takes a few minutes.', command: false }
			]
		}
	];
	return [...start, ...modules.flatMap((m) => m.nextSteps.map(toStep))];
}

function warnings(
	config: Config,
	resolution: Resolution,
	index: CatalogIndex,
	engine: Engine,
	ports: Port[]
): string[] {
	const result: string[] = [];
	if (!resolution.order.length && !resolution.missing.length) result.push('No module selected.');
	for (const name of resolution.unknown) result.push(`${name} is not in the catalog.`);
	if (resolution.cycle) result.push(`Modules depend on each other in a cycle at "${resolution.cycle}".`);

	const names = new Set<string>();
	for (const doc of config.custom) {
		const name = text(doc.name) || 'A custom module';
		for (const problem of problems(doc, engine.formats)) result.push(`${name}: ${problem}.`);
		if (names.has(name)) result.push(`Two custom modules are called ${name}.`);
		names.add(name);
		if (index.modules[name]) result.push(`Custom module ${name} replaces the catalog module of that name.`);
	}

	for (const [name, source] of resolution.source) {
		if (source.kind !== 'catalog') continue;
		const format = index.modules[name]?.versions[source.version]?.format;
		if (format !== undefined && !engine.formats.includes(format)) {
			result.push(`${name} ${source.version} uses format ${format}; image ${engine.image} reads ${engine.formats.join(', ')}.`);
		}
	}
	for (const module of resolution.order) {
		for (const variable of module.env) {
			if (variable.required && !effectiveValue(config, variable)) {
				result.push(`${variable.name} is required by ${module.name}; the container will not start without it.`);
			}
		}
	}
	const seen = new Map<string, string>();
	for (const port of ports) {
		const other = seen.get(port.port);
		if (other) result.push(`Port ${port.port} is used by ${other} and ${port.variable}.`);
		else seen.set(port.port, port.variable);
		if (!/^\d+$/.test(port.port)) result.push(`${port.variable} must be a port number.`);
	}
	if (!/^[a-zA-Z0-9][a-zA-Z0-9_.-]*$/.test(config.service)) {
		result.push('The service name may only contain letters, digits, dots, dashes and underscores.');
	}
	if (!/^\d+$/.test(config.puid) || !/^\d+$/.test(config.pgid)) result.push('PUID and PGID must be numbers.');
	if (!config.workspace.startsWith('/')) result.push('The workspace must be an absolute path.');
	if (resolution.order.some((m) => m.name === 'code-server') && !config.values.CODE_SERVER_PASSWORD) {
		result.push('code-server runs without a password; anyone who reaches the port can use the container.');
	}
	return result;
}

export function generate(
	config: Config,
	resolution: Resolution,
	index: CatalogIndex,
	engine: Engine
): Output {
	const modules = resolution.order;
	const ports = portsOf(config, modules);
	const configFiles: File[] = [
		{ path: 'config/agent.toml', text: agentToml(config, resolution) },
		...config.custom.map((doc) => ({ path: `config/modules/${text(doc.name)}.toml`, text: toToml(doc) }))
	];
	const hasSecrets = modules.some((m) => m.env.some((v) => v.type === 'secret'));
	const files: File[] = [
		{ path: 'compose.yaml', text: compose(config, ports, configFiles, hasSecrets) },
		{ path: '.env', text: envFile(config, modules) },
		...(config.inline ? [] : configFiles)
	];
	return {
		files,
		steps: steps(config, modules),
		warnings: warnings(config, resolution, index, engine, ports),
		ports
	};
}
